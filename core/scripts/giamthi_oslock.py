#!/usr/bin/env python3
"""Giám thị tier 2: root-owned OS lock that enforces HALT on every app.

Tier 1 (giamthi-watch.sh + halt-check hooks) only stops hosts that run this
repo's hooks. An app that never reads GIAMTHI_HALT.lock (for example the
Codex desktop app) keeps writing. Tier 2 is a root LaunchDaemon that watches
the lock file and, when it appears, sets the system-immutable flag (schg) on
the project tree and SIGSTOPs configured AI app processes owned by the
project owner. A normal user process cannot clear schg, so the lock holds
without any cooperation from the app. Only `yana-ai giamthi unlock` (a fresh
sudo password prompt) reverses it. See docs/adr/ADR-016.

macOS only for now. Design rules for the root script this module renders:
- it never runs git or anything else from the repo (git config such as
  core.fsmonitor would otherwise execute repo-controlled code as root);
- it uses `find -P -xdev` and `chflags -h` so symlinks are never followed;
- the daemon only locks; unlock is a separate, human-invoked action;
- root files are written through a pipe into root-only directories, never
  copied from a user-writable temp file (a same-user process could swap it
  while the human types the sudo password), and are read back and hashed.
"""

from __future__ import annotations

import hashlib
import os
import plistlib
import shlex
import stat
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

# Root-only locations: user-writable parents would let a same-user process
# swap the root script. /usr/local is avoided because Homebrew often chowns it.
HELPER_DIR = Path("/Library/PrivilegedHelperTools")
DAEMON_DIR = Path("/Library/LaunchDaemons")
STATE_ROOT = Path("/var/db/yana-giamthi")
# Fallback poll in case a WatchPaths event is missed; the script exits at once
# when no lock exists, so this is cheap.
FALLBACK_INTERVAL_SECONDS = 60
# Process names (exact, case-sensitive) frozen during HALT. The Codex desktop
# app runs its agent as a lowercase `codex` child process.
DEFAULT_FREEZE_TARGETS = ("Codex", "codex", "Cursor", "Antigravity", "Windsurf")
# Top-level build output and the watcher's own state stay writable so reports
# and heartbeats keep working during a HALT.
EXCLUDED_DIRS = ("node_modules", "target", ".claude/state")

CONSENT_PROMPT = (
    "  Also install Giám thị tier 2? It runs as root: during a HALT it makes this\n"
    "  project read-only for every app and pauses Codex/Cursor/Antigravity/Windsurf\n"
    "  until you unlock with your password. Requires sudo now. (Y/n) "
)

SCRIPT_TEMPLATE = """#!/bin/bash
# Generated by giamthi_oslock.py. Root-owned; do not edit. See ADR-016.
set -uo pipefail
PATH=/usr/bin:/bin:/usr/sbin:/sbin
REPO={repo}
OWNER_UID={uid}
STATE={state}
FREEZE=({names})
LOCK_REL=.claude/state/GIAMTHI_HALT.lock

log() {{ echo "$(date -u +%Y-%m-%dT%H:%M:%SZ) $*" >> "$STATE/oslock.log"; }}

enter_repo() {{
  # Refuse a swapped or foreign tree: resolve once, then work relative to it.
  [[ -d "$REPO" && ! -L "$REPO" ]] || {{ log "repo missing or symlink"; return 1; }}
  cd "$REPO" || return 1
  [[ "$(pwd -P)" == "$REPO" ]] || {{ log "repo path changed"; return 1; }}
  [[ "$(stat -f %u .)" == "$OWNER_UID" ]] || {{ log "repo owner changed"; return 1; }}
}}

set_flags() {{
  local flag="$1"
  find -P . -xdev \\( {prunes} \\) -prune -o -print0 | xargs -0 chflags -h "$flag" 2>/dev/null
  if [[ -e "$LOCK_REL" && ! -L .claude && ! -L .claude/state ]]; then
    chflags -h "$flag" "$LOCK_REL"
  fi
  return 0
}}

freeze_apps() {{
  local name pid
  # ${{A[@]+...}} form: macOS /bin/bash 3.2 treats an empty array as unbound under set -u.
  for name in ${{FREEZE[@]+"${{FREEZE[@]}}"}}; do
    for pid in $(pgrep -U "$OWNER_UID" -x "$name"); do
      kill -STOP "$pid" && echo "$pid" >> "$STATE/frozen"
    done
  done
}}

thaw_apps() {{
  [[ -f "$STATE/frozen" ]] || return 0
  local pid
  while read -r pid; do kill -CONT "$pid" 2>/dev/null; done < "$STATE/frozen"
  rm -f "$STATE/frozen"
}}

mkdir -p "$STATE" && chmod 0755 "$STATE"
case "${{1:-lock}}" in
  lock)
    enter_repo || exit 1
    [[ -e "$LOCK_REL" ]] || exit 0
    [[ -f "$STATE/locked" ]] && exit 0
    freeze_apps
    set_flags schg
    touch "$STATE/locked"
    log "LOCKED"
    ;;
  unlock)
    enter_repo || exit 1
    set_flags noschg
    rm -f "$LOCK_REL" "$STATE/locked"
    thaw_apps
    log "UNLOCKED by uid ${{SUDO_UID:-unknown}}"
    ;;
  *) echo "usage: $0 lock|unlock" >&2; exit 2 ;;
esac
"""


@dataclass(frozen=True)
class OsLockPaths:
    label: str
    script: Path
    plist: Path
    state: Path


def oslock_paths(target_id: str) -> OsLockPaths:
    label = f"com.yanaai.giamthi-oslock.{target_id}"
    return OsLockPaths(
        label=label,
        script=HELPER_DIR / f"{label}.sh",
        plist=DAEMON_DIR / f"{label}.plist",
        state=STATE_ROOT / target_id,
    )


def render_script(target: Path, owner_uid: int, state: Path, freeze: tuple[str, ...]) -> str:
    """Render the root script with every input baked in as a quoted literal."""
    return SCRIPT_TEMPLATE.format(
        repo=shlex.quote(str(target)),
        uid=int(owner_uid),
        state=shlex.quote(str(state)),
        names=" ".join(shlex.quote(name) for name in freeze),
        prunes=" -o ".join(f"-path {shlex.quote('./' + d)}" for d in EXCLUDED_DIRS),
    )


def render_plist(paths: OsLockPaths, target: Path) -> bytes:
    payload = {
        "Label": paths.label,
        "ProgramArguments": ["/bin/bash", str(paths.script), "lock"],
        "WatchPaths": [str(target / ".claude" / "state" / "GIAMTHI_HALT.lock")],
        "StartInterval": FALLBACK_INTERVAL_SECONDS,
        "RunAtLoad": True,
    }
    return plistlib.dumps(payload, sort_keys=False)


def _sudo(args: list[str], dry_run: bool, data: bytes | None = None) -> int:
    command = ["sudo", *args]
    if dry_run:
        print("DRY-RUN:", " ".join(shlex.quote(part) for part in command))
        return 0
    stdout = subprocess.DEVNULL if data is not None else None
    return subprocess.run(command, input=data, stdout=stdout, check=False).returncode


def _require_macos() -> None:
    if sys.platform != "darwin":
        raise RuntimeError("Giám thị tier 2 (OS lock) is macOS-only for now.")


def _require_root_only_dir(directory: Path) -> None:
    info = directory.stat()
    if info.st_uid != 0 or info.st_mode & (stat.S_IWGRP | stat.S_IWOTH):
        raise RuntimeError(f"{directory} must be owned by root and not group/other writable")


def _write_root_file(content: bytes, dest: Path, mode: str, dry_run: bool) -> None:
    """Pipe content straight into a root-owned file, then verify it by hash."""
    steps = (
        (["tee", str(dest)], content),
        (["chown", "root:wheel", str(dest)], None),
        (["chmod", mode, str(dest)], None),
    )
    for args, data in steps:
        if _sudo(args, dry_run, data) != 0:
            raise RuntimeError(f"sudo {args[0]} failed for {dest}")
    if dry_run:
        return
    if hashlib.sha256(dest.read_bytes()).digest() != hashlib.sha256(content).digest():
        _sudo(["rm", "-f", str(dest)], False)
        raise RuntimeError(f"{dest} content changed during install; removed it")


def install(target: Path, target_id: str, *, dry_run: bool) -> OsLockPaths:
    _require_macos()
    if not target.is_dir():
        raise RuntimeError(f"target does not exist or is not a directory: {target}")
    for directory in (HELPER_DIR, DAEMON_DIR):
        _require_root_only_dir(directory)
    paths = oslock_paths(target_id)
    script = render_script(target, target.stat().st_uid, paths.state, DEFAULT_FREEZE_TARGETS)
    _write_root_file(script.encode("utf-8"), paths.script, "0755", dry_run)
    _write_root_file(render_plist(paths, target), paths.plist, "0644", dry_run)
    _sudo(["launchctl", "bootout", "system", str(paths.plist)], dry_run)
    if _sudo(["launchctl", "bootstrap", "system", str(paths.plist)], dry_run) != 0:
        raise RuntimeError("launchctl bootstrap system failed for the OS lock daemon")
    return paths


def unlock(target_id: str, *, dry_run: bool) -> int:
    _require_macos()
    paths = oslock_paths(target_id)
    if not dry_run and not paths.script.exists():
        raise RuntimeError("OS lock is not installed; remove GIAMTHI_HALT.lock by hand instead.")
    if not dry_run and not sys.stdin.isatty():
        raise RuntimeError("unlock needs an interactive terminal: a human must type the sudo password.")
    # Drop any cached sudo credential so a fresh password is always required.
    _sudo(["-k"], dry_run)
    return _sudo([str(paths.script), "unlock"], dry_run)


def uninstall(target_id: str, *, dry_run: bool) -> OsLockPaths:
    _require_macos()
    paths = oslock_paths(target_id)
    if (paths.state / "locked").exists():
        raise RuntimeError("HALT is engaged under the OS lock; run `yana-ai giamthi unlock` first.")
    _sudo(["launchctl", "bootout", "system", str(paths.plist)], dry_run)
    _sudo(["rm", "-f", str(paths.plist), str(paths.script)], dry_run)
    return paths


def status(target_id: str) -> dict[str, object]:
    paths = oslock_paths(target_id)
    return {
        "oslock_installed": paths.plist.exists() and paths.script.exists(),
        "oslock_engaged": (paths.state / "locked").exists(),
        "oslock_label": paths.label,
    }


def offer_install(target: Path, target_id: str, *, dry_run: bool) -> None:
    """Offer tier 2 right after tier 1. Never fails the tier 1 install."""
    if sys.platform != "darwin":
        return
    if not dry_run and not sys.stdin.isatty():
        print("Giám thị tier 2 needs sudo; run later: yana-ai giamthi install-oslock .")
        return
    if not dry_run and input(CONSENT_PROMPT).strip().lower() not in {"", "y", "yes"}:
        print("Giám thị tier 2 skipped. Install later: yana-ai giamthi install-oslock .")
        return
    try:
        paths = install(target, target_id, dry_run=dry_run)
        print(f"Giám thị tier 2 ready: {paths.label}")
    except (RuntimeError, OSError) as error:
        print(f"Warning: Giám thị tier 2 not installed ({error}). "
              "Retry: yana-ai giamthi install-oslock .")
